-- 0069_app_schedule_success_mail.sql
-- 입력형 앱 예약의 '실행을 마치면 메일로 알림'(직원이 예약마다 고른다)
--
-- 배경:
--   예약(0048)은 실패·멈춤 때만 직원에게 메일을 보낸다. 주간 보고·월간 현황처럼 정기 결과를 받으려고 거는 예약이 많은데,
--   끝났는지는 앱 실행 기록을 열어 봐야 알았다.
--
-- 칸:
--   notify_on_success — 참이면 실행을 마칠 때마다 예약한 직원 본인에게 메일(앱·예약·시각·결과 보기 링크).
--                       **결과 글·입력값은 메일에 싣지 않는다**(자료는 시스템 안에 둔다). 기본 거짓(지금과 같음).
--
-- 추가만. 여러 번 적용해도 안전.
-- **코드 배포 전에 적용** — 새 코드가 예약 목록·만들기·고치기에서 이 칸을 읽고 쓴다(없으면 예약 화면이 503).
-- =============================================================

ALTER TABLE app_schedules
  ADD COLUMN IF NOT EXISTS notify_on_success boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN app_schedules.notify_on_success IS
  '실행을 마치면 예약한 직원에게 메일(링크만, 결과 글 없음) — 0069';
