-- 입력형 앱 예약의 '결과를 한글 파일로도 만들기'(직원이 예약마다 고른다)
--
-- 배경:
--   주간 보고처럼 정기 결과를 한글 파일로 쓰는 예약이 많은데, 결과는 대화로만 남아 매번 대화를 열어 '한글 파일 만들기'를 눌러야 했다.
--
-- 칸:
--   export_hwpx — 참이면 실행을 마칠 때마다 결과를 표준 보고서 한글(HWPX) 파일로 만들어 그 직원의 '대화에서 만든 파일'에 둔다.
--                 손으로 내보내기와 같은 규칙·같은 중복 열쇠(같은 답이면 한 벌)다. 기본 거짓(지금과 같음).
--
-- 추가만. 여러 번 적용해도 안전.
-- **코드 배포 전에 적용** — 새 코드가 예약 목록·만들기·고치기에서 이 칸을 읽고 쓴다(없으면 예약 화면이 503).
-- =============================================================

ALTER TABLE app_schedules
  ADD COLUMN IF NOT EXISTS export_hwpx boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN app_schedules.export_hwpx IS
  '실행을 마치면 결과를 표준 보고서 한글 파일로도 만든다(손 내보내기와 같은 규칙) — 0071';
